def normalize_language(lang: str | None) -> str:
    value = str(lang or "").strip().lower()
    return value if value in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def t(key: str, lang: str | None = None, **kwargs: object) -> str:
    normalized = normalize_language(lang)
    value = TEXT.get(normalized, TEXT[DEFAULT_LANGUAGE]).get(key)
    if value is None:
        value = TEXT[DEFAULT_LANGUAGE].get(key, key)
    return value.format(**kwargs) if kwargs else value


def category_tabs(lang: str | None = None) -> dict[str, str]:
    normalized = normalize_language(lang)
    return {
        "all": t("category_all", normalized),
        "makeup": t("category_makeup", normalized),
        "skincare": t("category_skincare", normalized),
        "sunscreen": t("category_sunscreen", normalized),
        "haircare": t("category_haircare", normalized),
        "bodycare": t("category_bodycare", normalized),
    }


def category_label(category: str, lang: str | None = None) -> str:
    key = f"category_{category}"
    return t(key, lang)
